    public static func defaultSwitches() -> [String: Bool] {
        Dictionary(uniqueKeysWithValues: catalog.map { ($0.id, $0.defaultEnabled) })
    }

    public static func effectiveSegments(
        for role: AgentPromptRole,
        switches: [String: Bool] = defaultSwitches()
    ) -> [PromptSegmentSpec] {
        catalog
            .filter { $0.roles.contains(role) && (switches[$0.id] ?? $0.defaultEnabled) }
            .sorted { $0.numericOrder < $1.numericOrder }
    }

    /// Composes the complete system instruction for the given agent role (`prober`, `teacher`, `practice`),
    /// always locking `TutorConstitution` at the root so safety, truthfulness, and learner agency can never
    /// be disabled by segment toggles.
    public static func composeSystemInstruction(
        role: AgentPromptRole,
        soul: AgentSoulDocument,
        guidanceStyle: TutorGuidanceStyle,
        switches: [String: Bool] = defaultSwitches(),
        extraContext: String = ""
    ) -> String {
        let baseSoul = soul.toSystemInstruction()
        let constitutionalRoot = TutorConstitution.applying(
            to: baseSoul,
            context: .learnerChat,
            guidanceStyle: guidanceStyle
        )

        var parts: [String] = [constitutionalRoot]
        let segments = effectiveSegments(for: role, switches: switches)
        for seg in segments {
            let trimmed = seg.markdownBody.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty {
                parts.append(trimmed)
            }
        }
        let trimmedExtra = extraContext.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmedExtra.isEmpty {
            parts.append(trimmedExtra)
        }
        return parts.joined(separator: "\n\n---\n\n")
    }
}
