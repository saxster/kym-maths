import Foundation

// MARK: - Modular, Inspectable & Parent-Toggled Prompt Segments (Ported from LearnHarness src/agent/prompts/)

public enum AgentPromptRole: String, Codable, CaseIterable, Sendable, Identifiable {
    case prober
    case teacher
    case practice

    public var id: String { rawValue }

    public var title: String {
        switch self {
        case .prober: return "Prober (Prerequisite Bracket Search)"
        case .teacher: return "Teacher (Minimal Tree & Predict → Teach → Check)"
        case .practice: return "Practitioner (Inactivity Constraint & R0–R5 Hints)"
        }
    }
}

public struct PromptSegmentSpec: Identifiable, Codable, Sendable, Equatable {
    public let id: String           // e.g. "05-method-unconditional-truths"
    public let numericOrder: Int
    public let title: String
    public let subtitle: String
    public let roles: [AgentPromptRole]
    public let defaultEnabled: Bool
    public let markdownBody: String

    public init(
        id: String,
        numericOrder: Int,
        title: String,
        subtitle: String,
        roles: [AgentPromptRole],
        defaultEnabled: Bool = true,
        markdownBody: String
    ) {
        self.id = id
        self.numericOrder = numericOrder
        self.title = title
        self.subtitle = subtitle
        self.roles = roles
        self.defaultEnabled = defaultEnabled
        self.markdownBody = markdownBody
    }
}

